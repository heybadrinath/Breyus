/**
 * Count total commodities in the hierarchy
 */
export function countCommodities(items: CommoditySeedItem[]): {
  total: number;
  mainstream: number;
  niche: number;
  folders: number;
} {
  let total = 0;
  let mainstream = 0;
  let niche = 0;
  let folders = 0;

  function traverse(items: CommoditySeedItem[]) {
    for (const item of items) {
      if (item.isMainstream === true) {
        mainstream++;
        total++;
      } else if (item.isMainstream === false) {
        niche++;
        total++;
      } else {
        folders++;
      }

      if (item.children) {
        traverse(item.children);
      }
    }
  }

  traverse(items);
  return { total, mainstream, niche, folders };
}

